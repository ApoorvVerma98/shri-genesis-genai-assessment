import type { ReconciliationReport } from "./assessment-audit.js";
import type { TraceabilityRequirement } from "./assessment-audit.js";

export const ASSESSMENT_PDF_REL = "docs/Gen AI_Creative Dev JD ShriGenesis.pdf";

/** Requirements extracted from the assessment PDF (no inferred extras). */
export function buildPdfTraceabilityRequirements(
  recon: ReconciliationReport,
  pdfAvailable: boolean,
): TraceabilityRequirement[] {
  const prov = recon.provenance;
  const provenanceBlocked = prov.unknown > 0;
  const structuralOk =
    recon.structuralValidation.failed === 0 && prov.missingSvg === 0 && recon.coverage.totalEntries >= 98;

  const r = (
    id: string,
    area: string,
    title: string,
    meaning: string,
    status: TraceabilityRequirement["status"],
    verification: TraceabilityRequirement["verification"],
    implementation: string[],
    evidence: string[],
    remainingWork: string,
  ): TraceabilityRequirement => ({
    id,
    area,
    title,
    meaning,
    status,
    verification,
    implementation,
    evidence,
    remainingWork,
  });

  return [
    r(
      "REQ-01",
      "§2 Core Assignment",
      "Approximately 100 SVG banners/infographics",
      "Build a script, application, or workflow that generates approximately 100 SVG banners or infographic designs across different topics and categories.",
      recon.coverage.totalEntries >= 98 && recon.coverage.totalEntries <= 102 ? "verified" : "partial",
      "automatic",
      ["apps/api/src/cli/batch.ts", "outputs/assessment/manifest.json"],
      [`${recon.coverage.totalEntries} canonical manifest entries`],
      recon.coverage.totalEntries !== 100 ? "Target exactly ~100 outputs per PDF." : "",
    ),
    r(
      "REQ-02",
      "§2 Core Assignment",
      "Programmatic generation pipeline",
      "The system should generate designs programmatically rather than requiring each banner to be manually created (topic, concept, copy, headings, supporting text, icons/illustrations, color, typography, layout, final SVG).",
      "implemented",
      "automatic",
      ["apps/api/src/pipeline.ts", "packages/svg-engine", "packages/ai"],
      ["Architecture in reports/technical-report.md"],
      "Demonstrate end-to-end on canonical collection with resolved provenance.",
    ),
    r(
      "REQ-03A",
      "§3A Topic and Content Generation",
      "Topic/category content generation",
      "Accept a topic, category, or content brief; generate suitable banner/infographic content with titles, subtitles, descriptions, key points; maintain hierarchy; avoid irrelevant/repetitive/grammatically incorrect content.",
      provenanceBlocked ? "partial" : prov.ai > 0 ? "demonstrated" : "partial",
      provenanceBlocked ? "manual" : "automatic",
      ["packages/ai", "packages/shared/src/topics.ts"],
      ["reports/ai-verify-batch.json", "reports/controlled-targeted-tests.json"],
      provenanceBlocked
        ? "Canonical per-entry AI/fallback unknown — do not infer from historical aggregates."
        : "",
    ),
    r(
      "REQ-03B",
      "§3B Template and Layout Generation",
      "Multiple design layouts",
      "Generate multiple design layouts (promotional, educational, statistics, step-by-step, quote, announcement, comparison, feature highlights, list-based, corporate/social); output must not be the same layout with only text/color changed.",
      recon.coverage.layouts.length >= 8 ? "verified" : "partial",
      "automatic",
      ["packages/svg-engine"],
      ["reports/category-coverage.json"],
      "",
    ),
    r(
      "REQ-03C",
      "§3C SVG Generation",
      "Valid scalable SVG files",
      "Each output must be a valid, scalable SVG with dimensions/viewBox, text/typography, shapes/vectors, icons where relevant, spacing/alignment, contrast, responsive scaling where applicable, clean structure; viewable in browsers and vector tools.",
      structuralOk ? "verified" : "partial",
      "automatic",
      ["packages/validation", "packages/svg-engine"],
      ["npm run validate:outputs", "reports/validation-summary.json"],
      "",
    ),
    r(
      "REQ-03D",
      "§3D Variety and Reusability",
      "Templates, styles, reusable components",
      "Demonstrate multiple templates, visual styles, content structures, compositions; reusable components; configurable colors, fonts, spacing, dimensions; extensible without major code changes.",
      "implemented",
      "manual",
      ["packages/shared/src/tokens.ts", "packages/svg-engine"],
      ["8 layout families", "12 categories"],
      "Manual review of meaningful variation across 100 outputs.",
    ),
    r(
      "REQ-04",
      "§4 Design Authenticity & SVG Quality",
      "Original, professional, clean SVG",
      "Designs must show intentional layouts, typography hierarchy, spacing, meaningful variation, relevant visuals; SVG must not contain prompt leakage, irrelevant metadata, hidden elements, scripts, broken defs; originality/IP rules apply.",
      "partial",
      "manual",
      ["packages/validation", "reports/technical-report.md"],
      ["reports/visual-qa-report.md"],
      "Manual originality and visual professional review pending.",
    ),
    r(
      "REQ-05",
      "§5 Generative AI Expectations",
      "Meaningful AI in workflow",
      "Demonstrate meaningful AI use (content, template selection, layout instructions, color/typography suggestions, structured elements, validation/refinement, variations). Simply calling an AI API and saving unstructured responses as SVG is not sufficient.",
      provenanceBlocked ? "partial" : "demonstrated",
      "manual",
      ["packages/ai/src/openai-compatible.ts", "packages/ai/src/factory.ts"],
      ["reports/ai-verify-batch.json", "reports/controlled-targeted-tests.json"],
      provenanceBlocked ? "Resolve canonical collection provenance via Phase E." : "",
    ),
    r(
      "REQ-06",
      "§6 Output Requirements",
      "~100 SVG outputs with organization",
      "Generate approximately 100 SVG outputs across topics/categories with design variation, generated content, consistent naming, organized folders; programmatic generation allowed but not simple duplicates with minor text/color changes.",
      recon.coverage.totalEntries === 100 && recon.exactDuplicateContentGroups === 0
        ? "verified"
        : "partial",
      "automatic",
      ["outputs/<category>/vf-*.svg", "outputs/assessment/manifest.json"],
      ["reports/category-coverage.json"],
      "",
    ),
    r(
      "REQ-06B",
      "§6 Submission Volume",
      "Preview set and contact sheet",
      "Submit ~100 SVGs, representative preview set of 10–15 designs, contact sheet or preview document if possible, source code, short technical report.",
      "partial",
      "manual",
      ["outputs/previews/contact-sheet.html", "npm run previews"],
      ["outputs/previews/contact-sheet.html", "reports/technical-report.md"],
      "Refresh contact sheet after Phase E; expand preview count to 10–15 if needed.",
    ),
    r(
      "REQ-07",
      "§8 Validation",
      "Validation and quality checks",
      "Validate SVG syntax, viewBox, required elements, text overflow, overlap, contrast, fonts/assets, broken references, duplicates, content completeness/relevance; automated or manual review.",
      structuralOk ? "verified" : "partial",
      "automatic",
      ["packages/validation", "npm run validate:outputs"],
      ["reports/validation-summary.json"],
      "Overlap/text overflow checks are heuristic only.",
    ),
    r(
      "REQ-08",
      "§9 Submission",
      "Source code and documentation",
      "Submit complete source, configuration, dependency files, env documentation, run instructions; do not include private API keys.",
      "verified",
      "manual",
      ["README.md", ".env.example", "package.json"],
      ["Repository tree"],
      "",
    ),
    r(
      "REQ-09",
      "§9 Execution Report",
      "Execution metrics report",
      "Include total designs generated, successful outputs, failed/partial outputs, total time, average time per design, API/model usage, validation results, known limitations.",
      "partial",
      "manual",
      ["apps/api/src/cli/batch.ts", "reports/execution-report.json"],
      ["reports/execution-run.json"],
      "Regenerate after completed Phase E batch; stale interrupted runs must not imply success.",
    ),
    r(
      "REQ-10",
      "§11 Evaluation",
      "Evaluation criteria coverage",
      "Review areas: Generative AI implementation, SVG generation, design quality, authenticity, variety, code quality, SVG cleanliness, originality, IP compliance, automation, validation, documentation.",
      pdfAvailable ? "partial" : "not_verified",
      "manual",
      ["reports/assessment-traceability.json"],
      ["Assessment Studio UI"],
      "Map each evaluation area to evidence in Requirements & Evidence view.",
    ),
    r(
      "REQ-11",
      "§12 Guidelines",
      "PDF source of truth",
      `Assessment specification: "${ASSESSMENT_PDF_REL}" (Shri Genesis Software Solutions — Gen AI Developer Practical Technical Assessment).`,
      pdfAvailable ? "verified" : "failed",
      pdfAvailable ? "manual" : "not_verified",
      [ASSESSMENT_PDF_REL],
      pdfAvailable ? [ASSESSMENT_PDF_REL] : [],
      pdfAvailable ? "" : "PDF path missing.",
    ),
    r(
      "REQ-12",
      "§12 Final Checklist",
      "Final candidate checklist items",
      "Checklist includes: automated SVG app, AI-based generation, multiple topics/categories, multiple templates, ~100 SVGs, representative preview, valid/scalable SVGs, typography/layout quality, metadata cleanup, originality, licensing, source/instructions, technical and execution reports, disclose AI tools.",
      "partial",
      "manual",
      ["reports/final-sign-off-checklist.md"],
      ["reports/assessment-traceability.md"],
      "Complete checklist after Phase E and manual QA.",
    ),
  ];
}
